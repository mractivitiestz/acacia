<?php

declare(strict_types=1);

namespace MrActivities\DesignSystem\Service;

/**
 * The palette formula of the design engine (site/assets/js/brand.js): the primary (ink) and the accent are used as they are,
 * the page sits on the palette's paper, every other tone is a tone of the primary's hue, and the text colours on brand and
 * accent are white or near-black by WCAG contrast. Run at build time by bin/palettes.php, never at request time.
 */
final class PaletteService
{
    private const string LIGHT = '#ffffff';
    private const string DARK = '#141414';

    /**
     * @param array{name: string, ink: string, accent: string, paper: string, night: string} $palette
     *
     * @return array<string, string> custom property name (without --) => colour
     */
    public function tones(array $palette): array
    {
        [$hue, $saturation] = $this->hsl($palette['ink']);
        $tone = fn (float $lightness, float $chroma): string => $this->hex($hue, min(1, max(.12, $saturation) * $chroma), $lightness / 100);
        $ink = $tone(11, .35);
        $panel = $palette['paper'];

        return [
            'bg' => $tone(95, .3),
            'panel' => $panel,
            'ink' => $ink,
            'muted' => $tone(36, .22),
            'line' => $tone(87, .25),
            'soft' => $tone(93, .45),
            'tint' => $tone(90, .6),
            'brand' => $palette['ink'],
            'on-brand' => $this->on($palette['ink']),
            'brand-text' => $this->contrast($palette['ink'], $panel) >= 4.5 ? $palette['ink'] : $ink,
            'accent' => $palette['accent'],
            'on-accent' => $this->on($palette['accent']),
            'accent-text' => $this->contrast($palette['accent'], $panel) >= 4.5 ? $palette['accent'] : $ink,
            'night' => $palette['night'],
            'on-night' => $this->on($palette['night']),
        ];
    }

    /**
     * @param list<array{name: string, ink: string, accent: string, paper: string, night: string}> $palettes
     */
    public function stylesheet(array $palettes, int $default): string
    {
        $css = "/* Generated by bin/palettes.php from palettes.json; do not edit. Palette {$default} is the default on :root, every palette answers to [data-palette=\"N\"]. */\n";
        foreach ($palettes as $palette) {
            $number = (int) strtok($palette['name'], ' ');
            $selector = ($number === $default ? ":root,\n" : '').'[data-palette="'.$number.'"]';
            $css .= "\n/* {$palette['name']} */\n{$selector} {\n";
            foreach ($this->tones($palette) as $name => $value) {
                $css .= "  --{$name}: {$value};\n";
            }
            $css .= "}\n";
        }

        return $css;
    }

    private function on(string $colour): string
    {
        return $this->contrast(self::LIGHT, $colour) >= $this->contrast(self::DARK, $colour) ? self::LIGHT : self::DARK;
    }

    private function contrast(string $a, string $b): float
    {
        $x = $this->luminance($a);
        $y = $this->luminance($b);

        return (max($x, $y) + .05) / (min($x, $y) + .05);
    }

    private function luminance(string $hex): float
    {
        $n = (int) hexdec(substr($hex, 1));
        $channel = static function (int $shift) use ($n): float {
            $v = (($n >> $shift) & 255) / 255;

            return $v <= .03928 ? $v / 12.92 : (($v + .055) / 1.055) ** 2.4;
        };

        return .2126 * $channel(16) + .7152 * $channel(8) + .0722 * $channel(0);
    }

    /** @return array{float, float, float} */
    private function hsl(string $hex): array
    {
        $n = (int) hexdec(substr($hex, 1));
        [$r, $g, $b] = array_map(static fn (int $shift): float => (($n >> $shift) & 255) / 255, [16, 8, 0]);
        $max = max($r, $g, $b);
        $min = min($r, $g, $b);
        $l = ($max + $min) / 2;
        if ($max === $min) {
            return [0.0, 0.0, $l];
        }
        $d = $max - $min;
        $s = $l > .5 ? $d / (2 - $max - $min) : $d / ($max + $min);
        $h = match ($max) {
            $r => ($g - $b) / $d + ($g < $b ? 6 : 0),
            $g => ($b - $r) / $d + 2,
            default => ($r - $g) / $d + 4,
        };

        return [$h * 60, $s, $l];
    }

    private function hex(float $h, float $s, float $l): string
    {
        $a = $s * min($l, 1 - $l);
        $f = static function (int $n) use ($h, $l, $a): float {
            $k = fmod($n + $h / 30, 12);

            return $l - $a * max(-1, min($k - 3, 9 - $k, 1));
        };

        return '#'.implode('', array_map(static fn (int $n): string => str_pad(dechex((int) round($f($n) * 255)), 2, '0', \STR_PAD_LEFT), [0, 8, 4]));
    }
}
