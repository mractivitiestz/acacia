<?php

declare(strict_types=1);

namespace MrActivities\DesignSystem\Service;

/**
 * Turns the entry (the layer order, then one @import url(...) layer(...) per file) into one stylesheet: the same order
 * line, then each file's rules inside its @layer block, in import order. Run at build time by bin/concat.php.
 */
final class StylesheetConcatService
{
    public const string ENTRY = 'mractivities.css';

    public function concat(string $assetsDir): string
    {
        $entry = (string) file_get_contents($assetsDir.'/'.self::ENTRY);
        if (!preg_match('/@layer\s+[^;{]+;/', $entry, $order)) {
            throw new \RuntimeException('The entry declares no layer order.');
        }
        $css = "/* mractivities/design-system: generated by bin/concat.php from assets/mractivities.css; do not edit. */\n".$order[0]."\n";
        preg_match_all("/@import url\\('([^']+)'\\) layer\\((\\w+)\\);/", $entry, $imports, \PREG_SET_ORDER);
        foreach ($imports as [, $file, $layer]) {
            $source = $this->rebaseUrls(rtrim((string) file_get_contents($assetsDir.'/'.$file)), \dirname($file));
            $css .= "\n/* {$file} */\n@layer {$layer} {\n{$source}\n}\n";
        }

        return $css;
    }

    /** A relative url() in assets/<dir>/x.css is rewritten to resolve from dist/, where the concatenation lives. */
    private function rebaseUrls(string $css, string $dir): string
    {
        return (string) preg_replace_callback('/url\((?![\'"]?(?:data:|https?:|\/|#))([\'"]?)([^)\'"]+)\1\)/', static function (array $m) use ($dir): string {
            $segments = explode('/', '.' === $dir ? 'assets' : 'assets/'.$dir);
            foreach (explode('/', $m[2]) as $segment) {
                match ($segment) {
                    '..' => array_pop($segments),
                    '.' => null,
                    default => $segments[] = $segment,
                };
            }

            return 'url('.$m[1].'../'.implode('/', $segments).$m[1].')';
        }, $css);
    }
}
